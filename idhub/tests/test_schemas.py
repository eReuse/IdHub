"""The Schemas and Context models.

No network here: everything is driven from the json files shipped in
``settings.SCHEMAS_DIR``.
"""
import json

from unittest.mock import Mock

from django.test import override_settings

from idhub.models import Context, Schemas, VerificableCredential
from test_support import factories
from test_support.base import IdHubTestCase


SCHEMA_FILE = 'membership-card.json'

# Every key under allOf[1].properties.credentialSubject.properties except
# 'id', which TERMS_PROTECTED reserves for the W3C context.
SUBJECT_TERMS = {
    'organisation', 'membershipType', 'membershipId', 'affiliatedSince',
    'affiliatedUntil', 'typeOfPerson', 'identityDocType', 'identityNumber',
    'firstName', 'lastName', 'role', 'email',
}


class SchemaManagerTest(IdHubTestCase):
    def test_create_adds_a_context_term_per_subject_property(self):
        factories.make_schema(SCHEMA_FILE)
        self.assertEqual(
            set(Context.objects.values_list('key', flat=True)), SUBJECT_TERMS
        )

    def test_create_skips_the_terms_the_w3c_context_already_defines(self):
        factories.make_schema(SCHEMA_FILE)
        self.assertIn('id', self.schema_subject_properties())
        self.assertFalse(Context.objects.filter(key='id').exists())

    def test_create_does_not_duplicate_existing_terms(self):
        factories.make_schema(SCHEMA_FILE)
        Schemas.objects.create(
            file_schema='second.json',
            data=factories.read_schema(SCHEMA_FILE),
            type='Membership Card',
        )
        self.assertEqual(Context.objects.count(), len(SUBJECT_TERMS))

    def test_create_skips_the_whole_walk_when_a_context_url_is_set(self):
        # A schema that ships its own @context file does not need the
        # autogenerated terms.
        Schemas.objects.create(
            file_schema=SCHEMA_FILE,
            data=factories.read_schema(SCHEMA_FILE),
            type='Membership Card',
            context='https://testserver/context/membership-card.jsonld',
        )
        self.assertFalse(Context.objects.exists())

    def test_create_without_data_adds_nothing(self):
        Schemas.objects.create(file_schema='empty.json', data='', type='x')
        self.assertFalse(Context.objects.exists())

    def schema_subject_properties(self):
        data = json.loads(factories.read_schema(SCHEMA_FILE))
        subject = data['allOf'][1]['properties']['credentialSubject']
        return subject['properties']


class SchemaAccessorsTest(IdHubTestCase):
    def setUp(self):
        super().setUp()
        self.schema = factories.make_schema(SCHEMA_FILE)

    def test_get_schema_parses_the_stored_json(self):
        self.assertEqual(self.schema.get_schema['title'], 'Membership Card')

    def test_get_schema_without_data(self):
        self.assertEqual(Schemas(data='').get_schema, {})

    def test_url_is_the_schema_id(self):
        self.assertEqual(
            self.schema.url,
            'https://idhub.pangea.org/vc_schemas/membership-card.json',
        )

    def test_get_type_is_the_title_without_spaces(self):
        expected = {
            'Membership Card': 'MembershipCard',
            'NGO Course Credential Schema': 'NgoCourseCredentialSchema',
            '': '',
        }
        for title, type in expected.items():
            with self.subTest(title=title):
                schema = Schemas(data=json.dumps({'title': title}))
                self.assertEqual(schema.get_type, type)

    def test_accessors_on_an_empty_schema(self):
        schema = Schemas(data='')
        self.assertEqual((schema.url, schema.get_type), ('', ''))

    def test_get_credential_subject_schema_is_a_standalone_json_schema(self):
        subject = self.schema.get_credential_subject_schema()
        self.assertEqual(
            subject['$schema'], 'https://json-schema.org/draft/2020-12/schema'
        )
        self.assertFalse(subject['additionalProperties'])
        self.assertEqual(set(subject['properties']) - {'id'}, SUBJECT_TERMS)

    def test_get_credential_subject_schema_drops_the_required_id(self):
        # The subject id is filled in at issue time, so it cannot be required
        # of the data the admin uploads.
        subject = self.schema.get_credential_subject_schema()
        self.assertNotIn('id', subject['required'])
        self.assertIn(
            'id',
            self.schema.get_data()['allOf'][1]['properties']
                ['credentialSubject']['required'],
        )

    def test_has_credentials_only_counts_issued_ones(self):
        did = factories.make_did(user=self.user)
        credential = factories.make_credential(self.user, self.schema, did)
        self.assertFalse(self.schema.has_credentials)

        credential.status = VerificableCredential.Status.ISSUED
        credential.save()
        self.assertTrue(self.schema.has_credentials)


class SchemaNameTest(IdHubTestCase):
    def setUp(self):
        super().setUp()
        self.schema = factories.make_schema(SCHEMA_FILE)

    def test_name_follows_the_active_language(self):
        expected = {
            'en': 'Membership Card',
            'es': 'Carnet de socio/a',
            'ca_ES': 'Carnet de soci/a',
            # 'ca' is remapped, because the schemas spell catalan 'ca_ES'
            # while LANGUAGE_CODE spells it 'ca'.
            'ca': 'Carnet de soci/a',
        }
        for language_code, name in expected.items():
            with self.subTest(language_code=language_code):
                with override_settings(LANGUAGE_CODE=language_code):
                    self.assertEqual(self.schema.name, name)

    def test_an_unknown_language_falls_back_to_the_last_entry(self):
        # _get_name_by_language reassigns `first` on every iteration, so the
        # fallback is the last name in the list despite the variable name.
        with override_settings(LANGUAGE_CODE='de'):
            self.assertEqual(self.schema.name, 'Carnet de socio/a')

    def test_the_request_language_is_unreachable_from_the_property(self):
        # _get_language_code takes a request, but `name` is a property and
        # properties cannot be called with arguments, so it is always None.
        request = Mock(LANGUAGE_CODE='es')
        self.assertEqual(self.schema._get_language_code(request), 'es')
        with override_settings(LANGUAGE_CODE='en'):
            self.assertEqual(self.schema.name, 'Membership Card')

    def test_name_of_a_schema_without_names(self):
        schema = Schemas(data=json.dumps({'title': 'x'}))
        self.assertEqual(schema.name, '')

    def test_name_setter_stores_json(self):
        schema = Schemas(data='')
        schema.name = [{'value': 'Hand written', 'lang': 'en'}]
        self.assertEqual(
            json.loads(schema._name), [{'value': 'Hand written', 'lang': 'en'}]
        )

    def test_description_is_returned_with_the_json_quoting_it_was_stored_with(self):
        # ImportSchemaForm.save json.dumps the description even though it is a
        # plain string, and nothing strips the quotes on the way out.
        self.assertTrue(self.schema.description.startswith('"'))
        self.assertEqual(
            json.loads(self.schema.description),
            json.loads(factories.read_schema(SCHEMA_FILE))['description'],
        )

    def test_description_setter_stores_the_value_verbatim(self):
        schema = Schemas(data='')
        schema.description = 'plain'
        self.assertEqual(schema._description, 'plain')


class LazyBackfillTest(IdHubTestCase):
    """``_update_and_get_field`` writes to the database while reading.

    Unreachable from ImportSchemaForm, which always fills both columns; it
    only matters for rows created before they existed.
    """

    def make_schema(self):
        return Schemas.objects.create(
            file_schema=SCHEMA_FILE,
            data=factories.read_schema(SCHEMA_FILE),
            type='Membership Card',
        )

    def test_reading_the_name_backfills_the_column(self):
        schema = self.make_schema()
        self.assertIsNone(schema._name)
        self.assertEqual(schema.name, 'Membership Card')
        self.assertTrue(Schemas.objects.get(pk=schema.pk)._name)

    def test_reading_the_description_backfills_the_column_unquoted(self):
        schema = self.make_schema()
        self.assertEqual(
            schema.description,
            json.loads(factories.read_schema(SCHEMA_FILE))['description'],
        )

    def test_the_backfilled_name_is_a_python_repr_and_cannot_be_read_back(self):
        # _update_model_field assigns the parsed list to a text column, so the
        # database ends up with "[{'value': ...}]" instead of json. On the
        # next read json.loads fails, the bare except swallows it, and
        # _get_name_by_language iterates the string character by character.
        schema = self.make_schema()
        schema.name

        stored = Schemas.objects.get(pk=schema.pk)._name
        with self.assertRaises(json.JSONDecodeError):
            json.loads(stored)
        with self.assertRaises(AttributeError):
            Schemas.objects.get(pk=schema.pk).name

    def test_an_empty_schema_is_never_written_to(self):
        schema = Schemas.objects.create(file_schema='e.json', data='', type='x')
        with self.assertNumQueries(0):
            self.assertEqual(schema.name, '')
            self.assertEqual(schema.description, '')


class ContextTest(IdHubTestCase):
    def test_get_context_maps_every_term_to_a_fragment_url(self):
        Context.objects.create(key='firstName')
        Context.objects.create(key='email')

        context = json.loads(Context.get_context('https://testserver'))
        self.assertEqual(context, {'@context': {
            'firstName': 'https://testserver/context/#firstName',
            'email': 'https://testserver/context/#email',
        }})

    def test_get_context_defaults_to_the_pangea_domain(self):
        Context.objects.create(key='email')
        self.assertEqual(
            json.loads(Context.get_context())['@context']['email'],
            'https://idhub.pangea.org/context/#email',
        )

    def test_get_context_ignores_any_path_in_the_domain(self):
        # urljoin with an absolute path drops whatever the domain carried.
        Context.objects.create(key='email')
        self.assertEqual(
            json.loads(Context.get_context('https://testserver/idhub/'))
                ['@context']['email'],
            'https://testserver/context/#email',
        )

    def test_get_context_without_any_term(self):
        self.assertEqual(json.loads(Context.get_context()), {'@context': {}})
